function actionsFor(
  boundary: string,
  dispatch: Q2DispatchCategory,
  mutation: "not_attempted" | "not_applied" | "applied" | "unknown",
  functional: "pending" | "succeeded" | "failed" | "inconclusive",
  evidence: "pending" | "available" | "failed" | "quarantined" | "suppressed",
  runtime: "healthy" | "recovery_required",
): Q1Action[] {
  const actions: Q1Action[] = [];
  if (dispatch === "possible")
    actions.push(
      ["B5", "B6", "B17", "B18", "B19"].includes(boundary)
        ? { type: "crossDispatch" }
        : { type: "beginPossibleDispatch" },
    );
  if (dispatch === "acknowledged") actions.push({ type: "crossDispatch" });
  if (boundary === "B17")
    actions.push({ type: "setProtectedProjection", canonical: mutation, projection: mutation });
  else if (mutation !== "not_attempted")
    actions.push({
      type: "establishMutation",
      truth: mutation,
      authoritative: mutation !== "unknown",
    });
  if (functional !== "pending") actions.push({ type: "recordFunctionalResult", truth: functional });
  if (evidence !== "pending")
    actions.push({ type: "settleEvidence", state: evidence, required: true });
  if (["B1", "B3", "B9", "B10", "B13", "B14", "B15", "B16", "B17"].includes(boundary))
    actions.push({ type: "setPersistence", state: "failed" });
  if (boundary === "B18") actions.push({ type: "loseAgentLease" });
  if (runtime === "recovery_required") actions.push({ type: "loseRuntimeLease" });
  if (boundary === "B20")
    actions.push({ type: "testOnlyCorrupt", path: "truth.telemetry", value: "failed" });
  return actions;
}

export const q2Scenarios: readonly Q2Scenario[] = definitions.map((entry, index) => {
  const [
    boundary,
    name,
    effect,
    phase,
    component,
    causeCategory,
    dispatch,
    mutation,
    functional,
    evidence,
    runtime,
    retryClass,
    recoveryOwner,
    invariantIds,
  ] = entry;
  return {
    id: `q2-${boundary.toLowerCase()}-${name.replaceAll(".", "-")}`,
    seed: 3001 + index,
    boundary,
    failpoint: { name, boundary, effect: effect as Q2FaultEffect, fireOnNth: 1, maxFires: 1 },
    phase,
    component,
    causeCategory: causeCategory as Q2CausalEnvelope["causeCategory"],
    dispatchCategory: dispatch,
    actions: actionsFor(boundary, dispatch, mutation, functional, evidence, runtime),
    expected: {
      functional,
      mutation,
      privacy: "pending",
      evidence,
      runtime,
      lifecycle: "running",
      dispatchCount:
        dispatch === "acknowledged" ||
        (dispatch === "possible" && ["B5", "B6", "B17", "B18", "B19"].includes(boundary))
          ? 1
          : 0,
    },
    retryClass: retryClass as Q2RetryClass,
    recoveryOwner,
    invariantIds: [...invariantIds],
  };
});

